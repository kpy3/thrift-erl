-module(rebar3_thrift_clean).

-moduledoc """
The `clean` provider of the `thrift` namespace: deletes every
generator-owned file (`.erl`/`.hrl` carrying the `Autogenerated by
Thrift Generator` banner) from the configured out dir.

Not meant for the command line: a default-namespace provider wins
rebar3's resolution, so `rebar3 thrift clean` is answered by the main
`thrift` provider. This one exists to be hooked into the project
clean — the consumer's `rebar.config`:

```erlang
{provider_hooks, [{post, [{clean, {thrift, clean}}]}]}
```
""".

-behaviour(provider).

-export([init/1, do/1, format_error/1]).

-spec init(rebar_state:t()) -> {ok, rebar_state:t()}.
init(State) ->
    Provider =
        providers:create([
            {name, clean},
            {namespace, thrift},
            {module, ?MODULE},
            {bare, true},
            {deps, [app_discovery]},
            {example, "rebar3 thrift clean"},
            {short_desc, "Remove generated Thrift sources from the project"},
            {desc,
                "Deletes every banner-marked .erl/.hrl from the thrift out dir; "
                "hook it into rebar3 clean with {provider_hooks, "
                "[{post, [{clean, {thrift, clean}}]}]}."}
        ]),
    {ok, rebar_state:add_provider(State, Provider)}.

-spec do(rebar_state:t()) -> {ok, rebar_state:t()} | {error, {rebar3_thrift_clean, term()}}.
do(State) ->
    Opts = rebar_state:get(State, thrift, []),
    OutDir = proplists:get_value(out_dir, Opts, "src"),
    case thrift_generator:clean(OutDir) of
        {ok, []} ->
            {ok, State};
        {ok, Paths} ->
            rebar_api:info("removed ~b generated thrift file(s) from ~ts", [length(Paths), OutDir]),
            {ok, State};
        {error, Reason} ->
            {error, {?MODULE, Reason}}
    end.

-spec format_error(term()) -> string().
%% Renders through the main provider's formatter: same diagnostics for
%% the CLI path and the hook path.
format_error(Reason) ->
    rebar3_thrift:format_error(Reason).
