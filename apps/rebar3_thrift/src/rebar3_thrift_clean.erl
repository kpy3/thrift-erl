-module(rebar3_thrift_clean).

-moduledoc """
The `clean` provider of the `thrift` namespace: deletes every
generator-owned file (`.erl`/`.hrl` carrying the `Autogenerated by
Thrift Generator` banner) from the configured out dir. The configured
out dir is validated through the generator's shared options contract
before anything is deleted: an invalid value fails the hook with the
same rendered diagnostic the library and the CLI report.

Not meant for the command line: a default-namespace provider wins
rebar3's resolution, so `rebar3 thrift clean` is answered by the main
`thrift` provider. This one exists to be hooked into the project
clean — the consumer's `rebar.config`:

```erlang
{provider_hooks, [{post, [{clean, {thrift, clean}}]}]}
```
""".

-behaviour(provider).

-export([init/1, do/1, format_error/1]).
%% Internal test seam for the out-dir validation (the do/1 path needs a
%% rebar3 state, which stays untested here like the rest of the host
%% API).
-export([out_dir/1]).

-spec init(rebar_state:t()) -> {ok, rebar_state:t()}.
init(State) ->
    Provider =
        providers:create([
            {name, clean},
            {namespace, thrift},
            {module, ?MODULE},
            {bare, true},
            {deps, [app_discovery]},
            {example, "rebar3 thrift clean"},
            {short_desc, "Remove generated Thrift sources from the project"},
            {desc,
                "Deletes every banner-marked .erl/.hrl from the thrift out dir; "
                "hook it into rebar3 clean with {provider_hooks, "
                "[{post, [{clean, {thrift, clean}}]}]}."}
        ]),
    {ok, rebar_state:add_provider(State, Provider)}.

-spec do(rebar_state:t()) -> {ok, rebar_state:t()} | {error, {rebar3_thrift_clean, term()}}.
do(State) ->
    Opts = rebar_state:get(State, thrift, []),
    case out_dir(Opts) of
        {ok, OutDir} ->
            case thrift_generator:clean(OutDir) of
                {ok, []} ->
                    {ok, State};
                {ok, Paths} ->
                    rebar_api:info("removed ~b generated thrift file(s) from ~ts", [length(Paths), OutDir]),
                    {ok, State};
                {error, Reason} ->
                    {error, {?MODULE, Reason}}
            end;
        {error, Reason} ->
            {error, {?MODULE, Reason}}
    end.

%% The hook path validates the configured out dir through the same
%% shared contract as the command path before anything is deleted: an
%% invalid value fails the provider with the shared reason and no file
%% is touched.

-doc false.
-spec out_dir(proplists:proplist()) -> {ok, file:filename_all()} | {error, term()}.
out_dir(Opts) ->
    case thrift_generator_options:normalize(#{out_dir => proplists:get_value(out_dir, Opts, "src")}) of
        {ok, #{out_dir := OutDir}} ->
            {ok, OutDir};
        {error, Reason} ->
            {error, Reason}
    end.

-spec format_error(term()) -> string().
%% Renders through the main provider's formatter: same diagnostics for
%% the CLI path and the hook path.
format_error(Reason) ->
    rebar3_thrift:format_error(Reason).
