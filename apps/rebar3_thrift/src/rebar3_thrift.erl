-module(rebar3_thrift).

-moduledoc """
rebar3 provider that runs the thrift_generator over IDL files declared
in the consumer's `rebar.config`:

```erlang
{thrift, [
    {files, ["src/my_api.thrift"]},  %% required, one or more IDL files
    {out_dir, "src"}                 %% optional, default "src"
]}
```

Every option mirrors the standalone generator's flags and is validated
by the generator's own normalizer, so a bad config fails with the same
diagnostic the CLI prints. Besides `out_dir`, five optional axes apply
only to definitions without an explicit annotation of their own:
`{repr, record|map|native}` (like `--repr`, the `erl.struct_type`
default), `{union_type, record|sum}` (like `--union-type`,
`erl.union_type`), `{set, list|sets|ordset}` (like `--set`, `erl.set`),
`{typedef_type, alias|nominal}` (like `--typedef-type`, `erl.type`)
and `{enum_case, preserve|lower}` (like `--enum-case`,
`erl.enum_case`); a file-wide namespace default overrides the option
for its file.

`rebar3 thrift` regenerates the Erlang sources for every file; files
whose content is already up to date are left untouched, so regenerating
an unchanged IDL does not churn mtimes. To run it before every
compilation, hook it in the consumer's `rebar.config`:

```erlang
{provider_hooks, [{pre, [{compile, {default, thrift}}]}]}
```

`rebar3 thrift --check` verifies instead of writing: it fails when any
generated artifact is missing or stale relative to the IDL — a CI
freshness gate.

`rebar3 thrift clean` deletes the generated files from the out dir:
every `.erl`/`.hrl` carrying the generator's `Autogenerated by Thrift
Generator` banner, so files orphaned by a removed service or a deleted
IDL go too. To run it on project cleanup, hook the namespaced clean
provider into `rebar3 clean`:

```erlang
{provider_hooks, [{post, [{clean, {thrift, clean}}]}]}
```
""".

-behaviour(provider).

-export([init/1, do/1, format_error/1]).
-export([thrift_gen_opts/1]).

-define(PROVIDER, thrift).
-define(DEPS, [app_discovery]).

-spec init(rebar_state:t()) -> {ok, rebar_state:t()}.
init(State) ->
    Provider =
        providers:create([
            {name, ?PROVIDER},
            {module, ?MODULE},
            {bare, true},
            {deps, ?DEPS},
            {example, "rebar3 thrift"},
            {opts, [
                {check, $c, "check", boolean,
                    "verify the generated sources are up to date instead of"
                    " writing; fails on missing or stale files"}
            ]},
            {short_desc, "Generate Erlang code from Thrift IDL files"},
            {desc,
                "Runs thrift_generator over the IDL files listed in "
                "the {thrift, [...]} section of rebar.config."}
        ]),
    {ok, rebar_state:add_provider(State, Provider)}.

-spec do(rebar_state:t()) -> {ok, rebar_state:t()} | {error, {rebar3_thrift, term()}}.
do(State) ->
    {Parsed, _Args} = rebar_state:command_parsed_args(State),
    Check = proplists:get_value(check, Parsed, false),
    Opts = rebar_state:get(State, thrift, []),
    case thrift_gen_opts(Opts) of
        {ok, GenOpts} ->
            run_task(State, Parsed, Check, Opts, GenOpts);
        {error, Reason} ->
            {error, {?MODULE, Reason}}
    end.

-spec run_task(
    rebar_state:t(),
    proplists:proplist(),
    boolean(),
    proplists:proplist(),
    thrift_generator:generate_opts()
) -> {ok, rebar_state:t()} | {error, {rebar3_thrift, term()}}.
%% `rebar3 thrift clean' reaches this provider as the global `task'
%% option — rebar3 folds leftover positional words into it, and a
%% default-namespace provider wins resolution over the thrift
%% namespace, so the namespaced clean provider is hook-only (see
%% rebar3_thrift_clean)
run_task(State, Parsed, Check, Opts, GenOpts) ->
    OutDir = maps:get(out_dir, GenOpts),
    case proplists:get_all_values(task, Parsed) of
        [] ->
            Files = proplists:get_value(files, Opts, []),
            case Files of
                [] ->
                    rebar_api:warn("~ts is configured but no thrift files are listed", [?PROVIDER]),
                    {ok, State};
                _ ->
                    Action =
                        case Check of
                            true -> fun check/2;
                            false -> fun generate/2
                        end,
                    try
                        lists:foreach(fun(File) -> Action(File, GenOpts) end, Files),
                        {ok, State}
                    catch
                        throw:{thrift_error, Reason} -> {error, {?MODULE, Reason}}
                    end
            end;
        ["clean"] when not Check ->
            try
                clean(OutDir),
                {ok, State}
            catch
                throw:{thrift_error, Reason} -> {error, {?MODULE, Reason}}
            end;
        ["clean"] ->
            {error, {?MODULE, clean_with_check}};
        Other ->
            {error, {?MODULE, {unknown_args, Other}}}
    end.

%% The {thrift, [...]} section is the generator's options map plus the
%% host-only `files' key: the proplist becomes a map (sans `files') and
%% is validated by thrift_generator_options:normalize/1, so a config
%% typo or an invalid value (including a string like "map" where the
%% atom is meant) fails the provider with the exact reason — and the
%% same rendered message — the library and the CLI report.

-doc """
Reads the `{thrift, [...]}` config section into the generator's
normalized `thrift_generator:generate_opts()` map: the host-only
`files` key is removed, every remaining entry is validated through
`thrift_generator_options:normalize/1` and the fully-defaulted map —
including `out_dir` (`"src"` by default) — is returned. A config typo
answers `{error, {unknown_option, Key}}`; an invalid value answers
`{error, {bad_option, {Key, Value, Allowed}}}`.
""".
-spec thrift_gen_opts(proplists:proplist()) ->
    {ok, thrift_generator:generate_opts()}
    | {error, {unknown_option, atom()} | {bad_option, {atom(), term(), [atom()]}}}.
thrift_gen_opts(Opts) ->
    thrift_generator_options:normalize(proplist_to_map(proplists:delete(files, Opts))).

%% First occurrence wins, exactly like the proplists lookup the provider
%% answered before the config became a map: a later duplicate neither
%% overrides an earlier value nor re-validates it.

-spec proplist_to_map(proplists:proplist()) -> map().
proplist_to_map(Proplist) ->
    lists:foldl(
        fun({Key, Value}, Acc) ->
            case maps:is_key(Key, Acc) of
                true -> Acc;
                false -> Acc#{Key => Value}
            end
        end,
        #{},
        Proplist
    ).

-spec generate(file:filename_all(), thrift_generator:generate_opts()) -> ok.
generate(File, GenOpts) ->
    case thrift_generator:generate(File, GenOpts) of
        {ok, Generated} ->
            rebar_api:info("~ts: generated ~b module(s) in ~ts", [
                File, length(Generated), maps:get(out_dir, GenOpts)
            ]),
            ok;
        {error, Reason} ->
            rebar_api:debug("~ts: generation failed", [File]),
            throw({thrift_error, Reason})
    end.

%% Deletes every banner-marked file from the out dir. The banner —
%% not the current IDL — decides, so orphans go too.

-spec clean(file:filename_all()) -> ok.
clean(OutDir) ->
    case thrift_generator:clean(OutDir) of
        {ok, []} ->
            rebar_api:info("no generated thrift sources in ~ts", [OutDir]),
            ok;
        {ok, Paths} ->
            lists:foreach(fun(Path) -> rebar_api:info("removed ~ts", [Path]) end, Paths),
            rebar_api:info("removed ~b generated thrift file(s) from ~ts", [length(Paths), OutDir]),
            ok;
        {error, Reason} ->
            rebar_api:debug("thrift clean failed", []),
            throw({thrift_error, Reason})
    end.

-spec check(file:filename_all(), thrift_generator:generate_opts()) -> ok.
check(File, GenOpts) ->
    case thrift_generator:check(File, GenOpts) of
        ok ->
            rebar_api:info("~ts: generated sources are up to date in ~ts", [
                File, maps:get(out_dir, GenOpts)
            ]),
            ok;
        {error, {stale, Paths}} ->
            rebar_api:debug("~ts: stale generated sources", [File]),
            throw({thrift_error, {stale, Paths}});
        {error, Reason} ->
            rebar_api:debug("~ts: check failed", [File]),
            throw({thrift_error, Reason})
    end.

-spec format_error(term()) -> string().
%% rebar3 calls this with the reason from {error, {rebar3_thrift,
%% Reason}} — renders through the CLI's formatter so the console shows
%% the same diagnostics the standalone tool prints.
format_error(clean_with_check) ->
    "the clean subcommand does not take --check";
format_error({unknown_args, Args}) ->
    io_lib:format("unrecognized arguments: ~ts (usage: rebar3 thrift [--check] [clean])", [
        string:join(Args, " ")
    ]);
format_error(Reason) ->
    unicode:characters_to_list(
        lists:flatten(thrift_generator_cli:format_error(Reason))
    ).
