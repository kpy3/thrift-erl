-module(thrift_generator_cli).

-moduledoc """
Command-line front end (escript entry point).

```
thrift_generator generate <file.thrift> [-o <out_dir>] [--repr record|map|native]
    [--union-type record|sum] [--set list|sets|ordset]
    [--typedef-type alias|nominal] [--enum-case preserve|lower]
    [--compact-errors]
thrift_generator check <file.thrift> [same options]
thrift_generator clean [-o <out_dir>]
```

The commands are explicit: a bare file operand, an implicit `generate`
and the legacy `--check` flag are rejected with the usage instead of
being folded into the grammar. Argument parsing rides on the stdlib
`argparse` module (usage/help included) under one dispatcher with a
spec per action; every action feeds the same normalized options map as
the `thrift_generator` library (`out_dir` plus the five axes). `generate`
runs the full pipeline (load with includes, semantic analysis, emit)
and writes the generated Erlang sources to `out_dir` (default: `src`).
The five option flags each pick the generated flavor for definitions
without an explicit annotation of their own: `--repr` the value
representation (`erl.struct_type`), `--union-type` the union
representation (`erl.union_type`), `--set` the in-process set
implementation (`erl.set`), `--typedef-type` the typedef flavor
(`erl.type`) and `--enum-case` the member atom casing (`erl.enum_case`);
a file-wide namespace default overrides the flag for its file. `check`
verifies instead of writing: every generated artifact must already
exist in `out_dir` with the exact content this input would produce —
drift (missing or stale files) exits 1, so the command works as a CI
freshness gate. `clean` deletes the generator's files from `out_dir` —
every `.erl`/`.hrl` carrying the `Autogenerated by Thrift Generator`
banner — and leaves everything else alone; a missing directory is a
successful no-op.

Errors render as rebar3/elp-style source excerpts (the offending line
under a gutter, a `╰──` marker naming the problem); `--compact-errors`
switches to one-line `path:line[:column]: message` entries. The rendering is
shared with the rebar3 plugin through `format_error/1`.
""".

-export([main/1]).
-export([command/0]).
-export([format_error/1]).

-define(PROGNAME, "thrift_generator").

-spec main([string()]) -> no_return().
main(RawArgs) ->
    Options = #{progname => ?PROGNAME},
    %% argparse demands a subcommand even for --help, so a bare help
    %% request is answered before parsing; everywhere else -h/--help
    %% rides on the shared help argument and wins over the action.
    case RawArgs of
        ["-h"] ->
            print_help([], Options);
        ["--help"] ->
            print_help([], Options);
        _ ->
            parse(RawArgs, Options)
    end.

-spec parse([string()], #{progname => string()}) -> no_return().
parse(Args, Options) ->
    case argparse:parse(Args, command(), Options) of
        {ok, #{help := true}, Path, _Cmd} ->
            print_help(tl(Path), Options);
        {ok, Parsed, [_Prog, Action], _Cmd} ->
            run(Action, Parsed, Options);
        {ok, _Parsed, [_Prog], _Cmd} ->
            parse_error("missing command", Options);
        {error, Reason} ->
            parse_error(argparse:format_error(Reason), Options)
    end.

-spec print_help([string()], #{progname => string()}) -> no_return().
print_help(Path, Options) ->
    io:put_chars([argparse:help(command(), Options#{command => Path}), $\n]),
    halt(0).

%% One dispatcher for the three actions. Generate and check share the
%% option surface and route through the library's generate/2 and
%% check/2; clean routes through clean/1.

-spec run(string(), argparse:arg_map(), #{progname => string()}) -> no_return().
run(Action, Parsed, Options) when Action =:= "generate"; Action =:= "check" ->
    case maps:get(file, Parsed, undefined) of
        undefined ->
            %% `file' stays optional in the spec so -h answers without
            %% it; a real invocation without the operand is a usage error
            parse_error("missing <file.thrift> operand", Options);
        File ->
            GenOpts = gen_opts(Parsed),
            Resolver = resolver(Parsed),
            case Action of
                "generate" -> generate(File, GenOpts, Resolver);
                "check" -> check(File, GenOpts, Resolver)
            end
    end;
run("clean", Parsed, _Options) ->
    clean(maps:get(out_dir, Parsed, <<"src">>), resolver(Parsed)).

%% The parsed generate/check options are exactly the library's options
%% map: argparse defaults and the library defaults agree, and the
%% CLI-only keys (file, help, compact_errors) never reach it.

-spec gen_opts(argparse:arg_map()) -> thrift_generator:generate_opts().
gen_opts(Parsed) ->
    #{
        out_dir => maps:get(out_dir, Parsed, <<"src">>),
        repr => maps:get(repr, Parsed, record),
        union_type => maps:get(union_type, Parsed, record),
        set => maps:get(set, Parsed, list),
        typedef_type => maps:get(typedef_type, Parsed, alias),
        enum_case => maps:get(enum_case, Parsed, preserve)
    }.

-spec resolver(argparse:arg_map()) -> thrift_generator_diagnostic:source_fun().
resolver(Parsed) ->
    case maps:get(compact_errors, Parsed, false) of
        true -> fun(_Path) -> {error, compact_errors} end;
        false -> auto
    end.

-spec parse_error(unicode:chardata(), #{progname => string()}) -> no_return().
parse_error(Message, Options) ->
    io:format(standard_error, "error: ~ts~n~ts~n", [
        Message, argparse:help(command(), Options)
    ]),
    halt(1).

-doc "The argparse dispatcher: one top-level help argument, and the generate/check/clean subcommand specs.".
-spec command() -> argparse:command().
command() ->
    #{
        arguments => [help_argument()],
        commands => #{
            "generate" => #{
                arguments => [file_argument() | generate_arguments()]
            },
            "check" => #{
                arguments => [file_argument() | generate_arguments()]
            },
            "clean" => #{
                arguments => [out_dir_argument(), compact_errors_argument()]
            }
        }
    }.

help_argument() ->
    #{
        name => help,
        short => $h,
        long => "-help",
        type => boolean,
        help => ["print this help and exit"]
    }.

%% The positional is optional in the spec so -h/--help stays answerable
%% without it; the dispatcher rejects a real run without the operand.

file_argument() ->
    #{
        name => file,
        required => false,
        help => {"<file.thrift>", ["IDL document to compile"]}
    }.

out_dir_argument() ->
    #{
        name => out_dir,
        short => $o,
        long => "-out-dir",
        type => binary,
        default => <<"src">>,
        help => {"[-o <out_dir>]", ["directory for generated .erl files (default: src)"]}
    }.

compact_errors_argument() ->
    #{
        name => compact_errors,
        long => "-compact-errors",
        type => boolean,
        help => [
            "print errors as one-line path:line[:column]: message"
            " entries instead of the default source-excerpt blocks"
        ]
    }.

%% The five generation axes plus -o and --compact-errors, named exactly
%% like the library options.

generate_arguments() ->
    [
        out_dir_argument(),
        #{
            name => repr,
            long => "-repr",
            type => {atom, [record, map, native]},
            default => record,
            help =>
                {"[--repr record|map|native]", [
                    "representation for definitions without an explicit"
                    " erl.struct_type annotation (default: record)"
                ]}
        },
        #{
            name => union_type,
            long => "-union-type",
            type => {atom, [record, sum]},
            default => record,
            help =>
                {"[--union-type record|sum]", [
                    "union representation for unions without an explicit"
                    " erl.union_type annotation (default: record)"
                ]}
        },
        #{
            name => set,
            long => "-set",
            type => {atom, [list, sets, ordset]},
            default => list,
            help =>
                {"[--set list|sets|ordset]", [
                    "in-process set implementation for sets without an"
                    " explicit erl.set annotation (default: list)"
                ]}
        },
        #{
            name => typedef_type,
            long => "-typedef-type",
            type => {atom, [alias, nominal]},
            default => alias,
            help =>
                {"[--typedef-type alias|nominal]", [
                    "typedef flavor for typedefs without an explicit"
                    " erl.type annotation (default: alias)"
                ]}
        },
        #{
            name => enum_case,
            long => "-enum-case",
            type => {atom, [preserve, lower]},
            default => preserve,
            help =>
                {"[--enum-case preserve|lower]", [
                    "member atom casing for enums without an explicit"
                    " erl.enum_case annotation (default: preserve)"
                ]}
        },
        compact_errors_argument()
    ].

generate(File, GenOpts, Resolver) ->
    case thrift_generator:generate(File, GenOpts) of
        {ok, Generated} ->
            io:format("Generated ~b module(s) in ~ts:~n", [
                length(Generated), unicode:characters_to_list(maps:get(out_dir, GenOpts))
            ]),
            lists:foreach(
                fun(#{path := Path} = Entry) ->
                    io:format("  ~ts~n", [unicode:characters_to_list(Path)]),
                    case Entry of
                        #{hrl := Hrl} when Hrl =/= undefined ->
                            io:format("  ~ts~n", [unicode:characters_to_list(Hrl)]);
                        _ ->
                            ok
                    end
                end,
                Generated
            ),
            halt(0);
        {error, Reason} ->
            io:format(standard_error, "~ts~n", [thrift_generator_diagnostic:format(Reason, Resolver)]),
            halt(1)
    end.

check(File, GenOpts, Resolver) ->
    case thrift_generator:check(File, GenOpts) of
        ok ->
            io:format("~ts: generated sources are up to date in ~ts~n", [
                unicode:characters_to_list(File), unicode:characters_to_list(maps:get(out_dir, GenOpts))
            ]),
            halt(0);
        {error, Reason} ->
            io:format(standard_error, "~ts~n", [thrift_generator_diagnostic:format(Reason, Resolver)]),
            halt(1)
    end.

clean(OutDir, Resolver) ->
    case thrift_generator:clean(OutDir) of
        {ok, []} ->
            io:format("no generator-owned files in ~ts~n", [unicode:characters_to_list(OutDir)]),
            halt(0);
        {ok, Paths} ->
            io:format("Removed ~b generator-owned files from ~ts:~n", [
                length(Paths), unicode:characters_to_list(OutDir)
            ]),
            lists:foreach(
                fun(Path) -> io:format("  ~ts~n", [unicode:characters_to_list(Path)]) end,
                Paths
            ),
            halt(0);
        {error, Reason} ->
            io:format(standard_error, "~ts~n", [thrift_generator_diagnostic:format(Reason, Resolver)]),
            halt(1)
    end.

%% The rendering itself lives in thrift_generator_diagnostic — the CLI
%% and the rebar3 plugin share one formatter.

format_error(Reason) ->
    thrift_generator_diagnostic:format(Reason).
