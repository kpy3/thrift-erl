%% erl_syntax helpers
%%--------------------------------------------------------------------

-spec var_fun() -> fun((string()) -> erl_syntax:syntaxTree()).
var_fun() ->
    fun erl_syntax:variable/1.

%% The module header: the autogenerated banner (the generator
%% application's version) plus the -module attribute. A plain
%% `Generated from <path>' comment names the source document; generated
%% modules carry no -moduledoc — the path in an attribute gave the
%% parser nothing the comment doesn't.

-spec header(module(), binary()) -> erl_syntax:forms().
header(ModuleName, SourcePath) ->
    [banner_comment(SourcePath), erl_syntax:attribute(erl_syntax:atom(module), [erl_syntax:atom(ModuleName)])].

%% The banner comment of every generated file (.erl and .hrl alike).

-spec banner_comment(binary()) -> erl_syntax:syntaxTree().
banner_comment(SourcePath) ->
    %% erl_pp prefixes every comment line with one `%': a bare `%'
    %% content renders as `%%', matching the section dividers.
    erl_syntax:comment([
        "%",
        "% Autogenerated by Thrift Generator (" ++ generator_vsn() ++ ")",
        "%",
        "% DO NOT EDIT UNLESS YOU ARE SURE THAT YOU KNOW WHAT YOU ARE DOING",
        "%",
        "% Generated from " ++ unicode:characters_to_list(SourcePath) ++ ". Do not edit."
    ]).

%% The version of the running generator application (the escript packs
%% it; tests run inside it).

-spec generator_vsn() -> string().
generator_vsn() ->
    application:load(thrift_generator),
    case application:get_key(thrift_generator, vsn) of
        {ok, Vsn} -> unicode:characters_to_list(Vsn);
        undefined -> "0"
    end.

%% The divider above every generated struct/union/exception/enum block:
%% a source comment naming the IDL construct the following forms were
%% generated from. The lines carry their own `%': prettypr prefixes
%% each comment line with exactly one.

-spec section_form(string()) -> erl_syntax:syntaxTree().
section_form(Label) ->
    Line = "---------------------------------------------------------------------",
    erl_syntax:comment(["% " ++ Line, "% " ++ Label, "% " ++ Line]).

%% The -moduledoc of a generated module that has something real to say
%% (the service handler/server/client contracts); types modules carry
%% the story in their forms and get none.

-spec moduledoc_form(binary()) -> erl_syntax:forms().
moduledoc_form(Doc) ->
    [
        erl_syntax:attribute(erl_syntax:atom(moduledoc), [
            erl_syntax:string(unicode:characters_to_list(Doc))
        ])
    ].

%% The attribute payload must be a term (tuples of {name, arity},
%% record field tuples, descriptor data) or a syntax tree; both print
%% as literal syntax.

-spec attribute(atom(), term() | erl_syntax:syntaxTree()) -> erl_syntax:syntaxTree().
attribute(Name, Payload) ->
    erl_syntax:attribute(
        erl_syntax:atom(Name),
        [abstract(Payload)]
    ).

%% -export() entries must be `arity_qualifier' trees — `abstract' tuples
%% print the same but `revert_forms' rejects them.

-spec export_form([{atom(), arity()}]) -> erl_syntax:syntaxTree().
export_form(Entries) ->
    qualifier_list_attribute(export, Entries).

%% The forms of one -export() attribute — none when there is nothing to
%% export (an empty attribute is noise, and a bare [] in a forms list
%% breaks revert_forms).

-spec exports_forms([{atom(), arity()}]) -> erl_syntax:forms().
exports_forms([]) ->
    [];
exports_forms(Entries) ->
    [export_form(Entries)].

%% -export_type() must be a raw erl_parse form: `erl_syntax:concrete'
%% leaves `arity_qualifier' trees unfolded, and erl_prettypr crashes
%% rendering the attribute from them (plain -export takes another path).

-spec export_type_form([{atom(), arity()}]) -> {attribute, erl_anno:anno(), export_type, [{atom(), arity()}]}.
export_type_form(Entries) ->
    {attribute, erl_anno:new(0), export_type, Entries}.

-spec qualifier_list_attribute(atom(), [{atom(), arity()}]) -> erl_syntax:syntaxTree().
qualifier_list_attribute(Name, Entries) ->
    erl_syntax:attribute(
        erl_syntax:atom(Name),
        [
            erl_syntax:list([
                erl_syntax:arity_qualifier(erl_syntax:atom(F), erl_syntax:integer(A))
             || {F, A} <- Entries
            ])
        ]
    ).

-spec fn_form(atom(), [erl_syntax:syntaxTree()]) -> erl_syntax:forms().
fn_form(Name, Clauses) ->
    [erl_syntax:function(erl_syntax:atom(Name), Clauses)].

%% The -doc attribute of a generated function: the definition's IDL doc
%% comment (when it carries one) followed by the built-in explanation of
%% the generated contract. Docs land in the docs chunk, so shell_docs
%% can explain the overloaded arities (encode/2 = protocol, decode/2 =
%% representation) without the consumer reading this emitter.

-spec doc_form(binary() | undefined, binary()) -> erl_syntax:forms().
doc_form(IdlDoc, BuiltIn) ->
    Text =
        case IdlDoc of
            undefined -> BuiltIn;
            Doc -> <<Doc/binary, "\n\n", BuiltIn/binary>>
        end,
    [erl_syntax:attribute(erl_syntax:atom(doc), [erl_syntax:string(unicode:characters_to_list(Text))])].

-spec fn_clause([erl_syntax:syntaxTree()], erl_syntax:syntaxTree()) -> erl_syntax:syntaxTree().
fn_clause(Patterns, Body) ->
    erl_syntax:clause(Patterns, none, [Body]).

%% The catch-all pattern: the variable `_`, not the atom `'_'` (which
%% `abstract/1` would build and which only matches itself).

-spec wildcard() -> erl_syntax:syntaxTree().
wildcard() ->
    erl_syntax:variable("_").

%% Binaries holding printable text print as `<<"text">>' at any depth —
%% byte-list form would swamp the generated descriptors, and the stock
%% `abstract/1' renders nested binaries as byte lists.

-spec abstract(term()) -> erl_syntax:syntaxTree().
abstract(Term) when is_binary(Term) ->
    case printable(Term) of
        true ->
            erl_syntax:binary([
                erl_syntax:binary_field(erl_syntax:string(unicode:characters_to_list(Term, utf8)))
            ]);
        false ->
            erl_syntax:abstract(Term)
    end;
abstract(Term) when is_tuple(Term) ->
    erl_syntax:tuple([abstract(Element) || Element <- tuple_to_list(Term)]);
abstract(Term) when is_list(Term) ->
    erl_syntax:list([abstract(Element) || Element <- Term]);
abstract(Term) when is_map(Term) ->
    erl_syntax:map_expr([
        erl_syntax:map_field_assoc(abstract(Key), abstract(Value))
     || Key := Value <- Term
    ]);
abstract(Term) ->
    erl_syntax:abstract(Term).

%% Printable per the unicode range: UTF-8 text (Cyrillic doc strings,
%% string constants) prints as `<<"текст">>', raw byte strings fall back
%% to the byte-list form.

-spec printable(binary()) -> boolean().
printable(Bin) ->
    case unicode:characters_to_list(Bin, utf8) of
        Chars when is_list(Chars) -> io_lib:printable_unicode_list(Chars);
        _ -> false
    end.

-spec map_field(atom(), erl_syntax:syntaxTree()) -> erl_syntax:syntaxTree().
map_field(Key, Value) ->
    erl_syntax:map_field_assoc(erl_syntax:atom(Key), Value).

-spec application(module(), atom(), [erl_syntax:syntaxTree()]) -> erl_syntax:syntaxTree().
application(Module, Name, Args) ->
    erl_syntax:application(
        erl_syntax:module_qualifier(erl_syntax:atom(Module), erl_syntax:atom(Name)),
        Args
    ).

%% Callback and spec attributes carry raw `erl_parse' type nodes
%% (`erl_prettypr' cannot lay them), so those attributes are built and
%% rendered as raw forms (`erl_pp'), while everything else stays trees.

%% The rendered source line budget: erl_pp lays raw forms out at 80
%% columns, and the `-doc'/`-moduledoc' strings are wrapped to the same
%% width.

-define(LINE_WIDTH, 80).

-spec format(erl_syntax:forms()) -> binary().
format(Forms) ->
    blank_around_comments(unicode:characters_to_binary(render([F || F <- Forms, F =/= []]))).

%% Top-level forms come out separated by an empty line — definitions
%% read as blocks — except where a form belongs to the one below it:
%% `-spec'/`-callback' contracts and `-doc' comments sit flush with
%% their definition, and comments get their spacing from
%% blank_around_comments.

render([]) ->
    [];
render([F]) ->
    [format_form(F)];
render([F | Rest]) ->
    [format_form(F) | render_from(F, Rest)].

render_from(Prev, [F | Rest]) ->
    case separated(F, Prev) of
        true -> ["\n", format_form(F) | render_from(F, Rest)];
        false -> [format_form(F) | render_from(F, Rest)]
    end;
render_from(_Prev, []) ->
    [].

separated(F, Prev) ->
    not (belongs_to_next(Prev) orelse is_comment(F) orelse is_comment(Prev)) andalso
        (is_function_form(F) orelse contract_or_doc(F)).

%% A `-spec'/`-callback' contract or a `-doc'/`-moduledoc' comment
%% belongs to the form that follows it.

belongs_to_next(Form) ->
    contract_or_doc(Form).

is_comment(Form) ->
    erl_syntax:is_tree(Form) andalso erl_syntax:type(Form) =:= comment.

is_function_form(Form) ->
    erl_syntax:is_tree(Form) andalso erl_syntax:type(Form) =:= function.

contract_or_doc({attribute, _Anno, Name, _Payload}) ->
    lists:member(Name, [doc, moduledoc, spec, callback]);
contract_or_doc(Form) ->
    case erl_syntax:is_tree(Form) andalso erl_syntax:type(Form) of
        attribute ->
            lists:member(attr_name(Form), [doc, moduledoc, spec, callback]);
        _ ->
            false
    end.

%% Every comment block in generated output (the banner, the section
%% dividers) is a reading landmark: a blank line separates it from the
%% code above and below. prettypr attaches comments flush to their form,
%% so the spacing is applied to the formatted text.

-spec blank_around_comments(binary()) -> binary().
blank_around_comments(Text) ->
    Lines = binary:split(Text, <<"\n">>, [global]),
    {Reversed, _} = lists:foldl(fun blank_line/2, {[], false}, Lines),
    unicode:characters_to_binary(lists:join(<<"\n">>, lists:reverse(Reversed))).

-spec blank_line(binary(), {[binary()], boolean()}) -> {[binary()], boolean()}.
blank_line(Line, {Acc, InComment}) ->
    Comment = starts_with_percent(Line),
    case {Comment, InComment} of
        %% first line of a comment block: separate it from the code
        %% above (unless the block opens the file)
        {true, false} ->
            {separated_above(Line, Acc), true};
        %% last line of a comment block: separate it from the code below
        {false, true} when Line =/= <<>> ->
            {[Line, <<>> | Acc], false};
        _ ->
            {[Line | Acc], Comment}
    end.

%% The blank before a block must not stack onto blank lines already
%% there (prettypr leaves none, but the raw-text hrl tail does); a
%% comment block opening the file gets no leading blank.

-spec separated_above(binary(), [binary()]) -> [binary()].
separated_above(Line, Acc) ->
    case drop_trailing_blanks(Acc) of
        [] -> [Line | Acc];
        Acc1 -> [Line, <<>> | Acc1]
    end.

-spec starts_with_percent(binary()) -> boolean().
starts_with_percent(<<"%", _/binary>>) ->
    true;
starts_with_percent(_) ->
    false.

-spec drop_trailing_blanks([binary()]) -> [binary()].
drop_trailing_blanks([<<>> | Rest]) ->
    drop_trailing_blanks(Rest);
drop_trailing_blanks(Acc) ->
    Acc.

-spec format_form(erl_syntax:forms() | erl_syntax:syntaxTree()) -> string().
format_form({raw_text, Text}) ->
    unicode:characters_to_list(Text);
format_form({tree, _, _, _} = Tree) ->
    case doc_form_source(Tree) of
        undefined -> [erl_prettypr:format(Tree), "\n"];
        Source -> [Source, "\n"]
    end;
format_form(RawForm) ->
    erl_pp:form(RawForm).

%% `-doc'/`-moduledoc' attributes carry string payloads, and
%% erl_prettypr lays an over-long string out by cutting it wherever the
%% column runs out — through the middle of `` `start_link/1' ''. Such
%% attributes are rendered by hand instead: words wrapped to the line
%% width, broken only at spaces, one string literal per line. The tree
%% stays a plain string attribute, so `revert_forms' and the in-memory
%% compile see the same doc every other tool does.

doc_form_source(Tree) ->
    case erl_syntax:type(Tree) of
        attribute ->
            case attr_name(Tree) of
                Name when Name =:= doc; Name =:= moduledoc ->
                    case attr_string(Tree) of
                        undefined -> undefined;
                        String -> wrap_doc_attribute(Name, String)
                    end;
                _ ->
                    undefined
            end;
        _ ->
            undefined
    end.

attr_name(Tree) ->
    case erl_syntax:concrete(erl_syntax:attribute_name(Tree)) of
        Name when is_atom(Name) -> Name;
        _ -> none
    end.

attr_string(Tree) ->
    case erl_syntax:attribute_arguments(Tree) of
        [Value] ->
            case erl_syntax:concrete(Value) of
                String when is_list(String) -> String;
                _ -> undefined
            end;
        _ ->
            undefined
    end.

wrap_doc_attribute(Name, String) ->
    Head = "-" ++ atom_to_list(Name) ++ "(\"",
    %% continuation lines open with the quote under the first one's
    Cont = lists:duplicate(length(Head) - 1, $\s) ++ "\"",
    %% the last line also closes the literal and the attribute
    Budget = ?LINE_WIDTH - length(Head) - 3,
    [First | Rest] = doc_chunks(String, Budget),
    Lines = [Head ++ First ++ "\"" | [Cont ++ Chunk ++ "\"" || Chunk <- Rest]],
    lists:concat(lists:join("\n", close_attribute(Lines))).

close_attribute([Line]) ->
    [Line ++ ")."];
close_attribute([Line | Rest]) ->
    [Line | close_attribute(Rest)].

%% The chunks of one string literal, wrapped at word boundaries; the
%% literals concatenate back to the original text — a space rides at
%% the end of a chunk broken mid-paragraph, a `\n' escape at the end of
%% a paragraph's last chunk.

doc_chunks(String, Budget) ->
    Paragraphs = [escape_doc(P) || P <- string:split(String, "\n", all)],
    Wrapped = [wrap_words(string:split(P, " ", all), Budget) || P <- Paragraphs],
    lists:append([paragraph_chunks(Chunks, Last) || {Last, Chunks} <- with_last(Wrapped)]).

with_last(Wrapped) ->
    Last = length(Wrapped),
    lists:zip([I =:= Last || I <- lists:seq(1, Last)], Wrapped).

paragraph_chunks([Only], true) ->
    [Only];
paragraph_chunks([Only], false) ->
    [Only ++ "\\n"];
paragraph_chunks(Chunks, Last) ->
    Body = lists:sublist(Chunks, length(Chunks) - 1),
    [Chunk ++ " " || Chunk <- Body] ++ [last_paragraph_chunk(lists:last(Chunks), Last)].

last_paragraph_chunk(Chunk, true) ->
    Chunk;
last_paragraph_chunk(Chunk, false) ->
    Chunk ++ "\\n".

wrap_words(Words, Budget) ->
    {Lines, Current} =
        lists:foldl(
            fun
                (Word, {Acc, []}) ->
                    {Acc, Word};
                (Word, {Acc, Current}) ->
                    case length(Current) + 1 + length(Word) =< Budget of
                        true -> {Acc, Current ++ " " ++ Word};
                        false -> {Acc ++ [Current], Word}
                    end
            end,
            {[], []},
            Words
        ),
    Lines ++ [Current].

escape_doc(String) ->
    [
        case Char of
            $" -> "\\\"";
            $\\ -> "\\\\";
            _ -> Char
        end
     || Char <- String
    ].
